import React, { useState, useEffect } from 'react';
import { api, money } from './api.js';
import { Icon } from './ui.jsx';
import { Modal, Field } from './components.jsx';

export default function WhatsAppModal({ doc, party, business, onClose, toast }) {
  const defaultPhone = (party && party.phone) || (doc && doc.party_phone) || '';
  const [phone, setPhone] = useState(defaultPhone);
  const [message, setMessage] = useState('');
  const [copied, setCopied] = useState(false);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    let active = true;
    if (!doc) return;
    api.share(doc.id, { phone })
      .then((res) => {
        if (!active) return;
        setMessage(res.message);
        if (!phone && res.phone) setPhone(res.phone);
      })
      .catch((e) => {
        if (!active) return;
        const pdfUrl = `${window.location.origin}/api/documents/${doc.id}/pdf`;
        const fallback = `Dear ${doc.party_name || 'Customer'},\n\nTax Invoice *${doc.number}* for *${money(doc.total)}* has been generated by *${business.name}*.\n\n📄 View / Download Bill: ${pdfUrl}\n${business.upi_id ? '💳 Pay via UPI: ' + business.upi_id + '\n' : ''}\nThank you for your business!`;
        setMessage(fallback);
      })
      .finally(() => { if (active) setLoading(false); });
    return () => { active = false; };
  }, [doc.id]);

  const cleanDigits = String(phone || '').replace(/\D/g, '');
  const cleanPhone = cleanDigits.length === 10
    ? '91' + cleanDigits
    : (cleanDigits.startsWith('91') && cleanDigits.length === 12 ? cleanDigits : (cleanDigits ? '91' + cleanDigits : ''));

  const waLink = cleanPhone ? `https://wa.me/${cleanPhone}?text=${encodeURIComponent(message)}` : null;
  const smsLink = cleanDigits ? `sms:${cleanDigits}?body=${encodeURIComponent(message)}` : null;

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(message);
      setCopied(true);
      setTimeout(() => setCopied(false), 1800);
      if (toast) toast('Message copied to clipboard', 'ok');
    } catch (e) {}
  };

  const openWhatsApp = () => {
    if (!cleanPhone) {
      if (toast) toast('Please enter a valid 10-digit mobile number', 'err');
      return;
    }
    window.open(waLink, '_blank', 'noopener,noreferrer');
    if (toast) toast(`Opening WhatsApp for ${cleanPhone}…`, 'ok');
    if (onClose) onClose();
  };

  return (
    <Modal
      title="Send Bill via WhatsApp"
      sub={`${doc.number} · ${money(doc.total)} · ${doc.party_name || 'Walk-in Customer'}`}
      size=""
      onClose={onClose}
      footer={
        <>
          <button type="button" className="btn" onClick={onClose}>Close</button>
          <button type="button" className="btn" onClick={copy}>
            {copied ? '✓ Copied' : '📋 Copy message'}
          </button>
          <button
            type="button"
            className="btn green"
            style={{ fontWeight: 650, display: 'inline-flex', alignItems: 'center', gap: 6 }}
            onClick={openWhatsApp}
            disabled={!cleanDigits}
          >
            <Icon.whatsapp size={16} /> Send to WhatsApp
          </button>
        </>
      }
    >
      <div className="form-grid" style={{ marginBottom: 12 }}>
        <Field label="Customer WhatsApp Mobile Number" req full hint="Enter 10-digit Indian mobile number (e.g. 9845012345)">
          <div style={{ display: 'flex', alignItems: 'center', gap: 6 }}>
            <span style={{
              background: 'var(--panel)', border: '1px solid var(--line)', borderRadius: 8,
              padding: '8px 12px', fontSize: 13, fontWeight: 600, color: 'var(--muted)'
            }}>+91</span>
            <input
              className="input"
              type="tel"
              placeholder="98450 12345"
              style={{ flex: 1, fontSize: 14, fontWeight: 600, letterSpacing: 0.5 }}
              value={phone}
              onChange={(e) => setPhone(e.target.value)}
              autoFocus
            />
          </div>
        </Field>

        <Field label="WhatsApp Message Preview" full hint="You can customize or add a personal note before sending">
          <textarea
            className="input"
            rows={7}
            style={{ fontSize: 12.5, lineHeight: 1.45, fontFamily: 'inherit' }}
            value={message}
            onChange={(e) => setMessage(e.target.value)}
            disabled={loading}
          />
        </Field>
      </div>

      <div style={{
        background: 'var(--panel)', border: '1px solid var(--line)', borderRadius: 8,
        padding: '10px 14px', display: 'flex', alignItems: 'center', justifyContent: 'space-between', flexWrap: 'wrap', gap: 8
      }}>
        <div style={{ fontSize: 12, color: 'var(--muted)' }}>
          {cleanPhone ? (
            <span>Ready to send to: <b style={{ color: 'var(--ink)' }}>+{cleanPhone}</b></span>
          ) : (
            <span style={{ color: 'var(--amber)' }}>⚠️ Enter customer's mobile number above to enable 1-click WhatsApp sending</span>
          )}
        </div>
        <div style={{ display: 'flex', gap: 6 }}>
          {smsLink && (
            <a className="btn sm" href={smsLink} title="Send standard SMS">
              <Icon.phone size={13} /> SMS
            </a>
          )}
          <a
            className="btn sm"
            href={`${window.location.origin}/api/documents/${doc.id}/pdf`}
            target="_blank"
            rel="noreferrer"
            title="Download PDF Invoice"
          >
            <Icon.download size={13} /> PDF link
          </a>
        </div>
      </div>
    </Modal>
  );
}
